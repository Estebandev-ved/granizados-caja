-- 1) «Ya le pagué» resta de Mi plata, pero solo los pagos nuevos (los de antes siguen siendo solo constancia).
--    El efectivo sale de la caja o de la casa (lugar_efectivo) y la parte por Nequi, de Nequi.
ALTER TABLE pago_vendedor ADD COLUMN mueve_plata BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE pago_vendedor ADD COLUMN lugar_efectivo VARCHAR(10) NOT NULL DEFAULT 'CAJA';
-- Lo que se le descontó en ese pago por préstamos y por faltantes (queda en la constancia).
ALTER TABLE pago_vendedor ADD COLUMN prestamos BIGINT NOT NULL DEFAULT 0;
ALTER TABLE pago_vendedor ADD COLUMN faltantes BIGINT NOT NULL DEFAULT 0;

-- 2) Préstamos (adelantos) al trabajador: salen de Mi plata y se le descuentan en el próximo pago (pago_id).
CREATE TABLE prestamo_vendedor (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id  BIGINT       NOT NULL DEFAULT 1,
    vendedor_id BIGINT       NOT NULL REFERENCES vendedor (id),
    monto       BIGINT       NOT NULL,
    lugar       VARCHAR(10)  NOT NULL,
    nota        VARCHAR(120),
    creado_en   TIMESTAMP WITH TIME ZONE NOT NULL,
    pago_id     BIGINT REFERENCES pago_vendedor (id),
    CONSTRAINT ck_prestamo_vendedor_monto CHECK (monto > 0)
);
CREATE INDEX ix_prestamo_vendedor ON prestamo_vendedor (negocio_id, vendedor_id, creado_en);

-- 3) Faltantes: granizados de la carga que no aparecieron al cuadrar. Se le cobran al precio de venta.
ALTER TABLE venta DROP CONSTRAINT ck_venta_metodo;
ALTER TABLE venta ADD CONSTRAINT ck_venta_metodo
    CHECK (metodo IN ('NEQUI', 'EFECTIVO', 'FIADO', 'MIXTO', 'REGALO', 'CONSUMO', 'FALTANTE'));

-- 4) Foto del comprobante de una venta (Nequi o transferencia). Se guarda comprimida y se borra sola a los 30 días.
CREATE TABLE comprobante (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id  BIGINT       NOT NULL DEFAULT 1,
    venta_uid   VARCHAR(64)  NOT NULL,
    vendedor_id BIGINT,
    tipo        VARCHAR(40)  NOT NULL,
    imagen      BYTEA        NOT NULL,
    creado_en   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_comprobante_venta UNIQUE (negocio_id, venta_uid)
);
CREATE INDEX ix_comprobante_creado ON comprobante (negocio_id, creado_en);
