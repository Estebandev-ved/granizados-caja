-- Plan de ventas en la calle: salidas a vender a un lugar (parque, esquina), lugares con su punto en el mapa y alertas SOS.
-- Una venta de la calle lleva el uid de su salida (no es llave foránea: la venta puede llegar antes que la salida si no había señal).
ALTER TABLE venta ADD COLUMN salida_uid VARCHAR(64);
CREATE INDEX ix_venta_salida ON venta (negocio_id, salida_uid);

-- Un lugar donde se ha vendido o se quiere probar. lat/lng es donde se paró quien empezó la primera salida ahí.
CREATE TABLE lugar_venta (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id BIGINT       NOT NULL DEFAULT 1,
    nombre     VARCHAR(60)  NOT NULL,
    lat        DOUBLE PRECISION,
    lng        DOUBLE PRECISION,
    nota       VARCHAR(120),
    creado_en  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_lugar_venta_nombre UNIQUE (negocio_id, nombre)
);

-- Una salida: quién fue, a qué lugar, de cuándo a cuándo, cuánto gastó en pasajes y qué pasó.
-- Las unidades y la plata salen de las ventas que llevan su uid (nada se guarda dos veces).
CREATE TABLE salida_calle (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id  BIGINT      NOT NULL DEFAULT 1,
    client_uid  VARCHAR(64) NOT NULL,
    lugar_id    BIGINT      NOT NULL,
    -- null = la hizo el dueño
    vendedor_id BIGINT,
    inicio      TIMESTAMP WITH TIME ZONE NOT NULL,
    fin         TIMESTAMP WITH TIME ZONE,
    lat_ini     DOUBLE PRECISION,
    lng_ini     DOUBLE PRECISION,
    pasaje      BIGINT      NOT NULL DEFAULT 0,
    -- Salida de prueba: el dueño la mandó a probar el lugar y paga el pasaje completo
    prueba      BOOLEAN     NOT NULL DEFAULT FALSE,
    incidentes  VARCHAR(80),
    nota        VARCHAR(200),
    CONSTRAINT uq_salida_calle_uid UNIQUE (negocio_id, client_uid),
    CONSTRAINT ck_salida_calle_pasaje CHECK (pasaje >= 0)
);
CREATE INDEX ix_salida_calle_inicio ON salida_calle (negocio_id, inicio);

-- El botón de alerta del trabajador: hurto, policía o ayuda. Queda constancia de dónde y cuándo.
CREATE TABLE alerta_sos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id  BIGINT      NOT NULL DEFAULT 1,
    client_uid  VARCHAR(64) NOT NULL,
    vendedor_id BIGINT,
    tipo        VARCHAR(10) NOT NULL,
    lugar       VARCHAR(60),
    lat         DOUBLE PRECISION,
    lng         DOUBLE PRECISION,
    creada_en   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_alerta_sos_uid UNIQUE (negocio_id, client_uid),
    CONSTRAINT ck_alerta_sos_tipo CHECK (tipo IN ('HURTO', 'POLICIA', 'AYUDA'))
);
CREATE INDEX ix_alerta_sos_fecha ON alerta_sos (negocio_id, creada_en);

