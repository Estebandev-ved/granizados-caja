-- Rastro de las ventas que se borran (deshacen): qué era, quién la había hecho, quién la borró y cuándo. Así una venta
-- en efectivo que se cobró y después se borró no desaparece sin dejar huella. Es solo constancia: no mueve nada.
CREATE TABLE venta_borrada (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id        BIGINT       NOT NULL DEFAULT 1,
    venta_uid         VARCHAR(64)  NOT NULL,
    -- De quién era la venta (null = del dueño) y quién la borró (null = el dueño)
    vendedor_id       BIGINT,
    borro_vendedor_id BIGINT,
    sabor             VARCHAR(120) NOT NULL,
    cantidad          INT          NOT NULL,
    total             BIGINT       NOT NULL,
    metodo            VARCHAR(20)  NOT NULL,
    vendida_en        TIMESTAMP WITH TIME ZONE NOT NULL,
    borrada_en        TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_venta_borrada_fecha ON venta_borrada (negocio_id, borrada_en);

-- Lo que el dueño saca del negocio para él (su sueldo). Resta de Mi plata pero no es gasto: la ganancia no cambia.
CREATE TABLE retiro (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id  BIGINT       NOT NULL DEFAULT 1,
    client_uid  VARCHAR(64)  NOT NULL,
    monto       BIGINT       NOT NULL,
    lugar       VARCHAR(10)  NOT NULL,
    nota        VARCHAR(80),
    creado_en   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_retiro_uid UNIQUE (negocio_id, client_uid),
    CONSTRAINT ck_retiro_monto CHECK (monto > 0),
    CONSTRAINT ck_retiro_lugar CHECK (lugar IN ('CAJA', 'CASA', 'NEQUI'))
);
CREATE INDEX ix_retiro_fecha ON retiro (negocio_id, creado_en);
