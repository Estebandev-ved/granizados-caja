-- Equipo: trabajadores que venden con su propio PIN dentro de la misma caja (mismo negocio, mismo inventario).
-- Cada venta guarda quién la hizo; la carga del día (cuánto saca cada uno a vender) vive en el servidor para que
-- se vea igual en cualquier celular y solo cuente las ventas de ese trabajador.
CREATE TABLE vendedor (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id    BIGINT       NOT NULL DEFAULT 1,
    nombre        VARCHAR(60)  NOT NULL,
    pin_hash      VARCHAR(100) NOT NULL,
    comision_pct  INTEGER      NOT NULL DEFAULT 0,
    activo        BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_vendedor_comision CHECK (comision_pct BETWEEN 0 AND 100)
);

CREATE TABLE carga_vendedor (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id    BIGINT  NOT NULL DEFAULT 1,
    vendedor_id   BIGINT  NOT NULL REFERENCES vendedor (id),
    producto_id   BIGINT  NOT NULL REFERENCES producto (id),
    dia           DATE    NOT NULL,
    llevo         INTEGER NOT NULL,
    -- Desde cuándo cuentan las ventas contra esta carga (cuando se la entregaron)
    desde         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_carga_vendedor UNIQUE (negocio_id, vendedor_id, producto_id, dia),
    CONSTRAINT ck_carga_llevo CHECK (llevo > 0)
);

ALTER TABLE venta ADD COLUMN vendedor_id BIGINT REFERENCES vendedor (id);
CREATE INDEX ix_venta_vendedor ON venta (vendedor_id, creada_en);
