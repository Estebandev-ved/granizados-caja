-- Fiados: ventas que se cobran después. La venta queda registrada (stock y ganancia) con método FIADO
-- y la deuda guarda quién debe, su celular (opcional, para recordarle por WhatsApp) y cuánto.
ALTER TABLE venta DROP CONSTRAINT ck_venta_metodo;
ALTER TABLE venta ADD CONSTRAINT ck_venta_metodo CHECK (metodo IN ('NEQUI', 'EFECTIVO', 'FIADO'));

CREATE TABLE deuda (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id  BIGINT       NOT NULL DEFAULT 1,
    venta_uid   VARCHAR(64)  NOT NULL,
    cliente     VARCHAR(60)  NOT NULL,
    telefono    VARCHAR(20),
    monto       BIGINT       NOT NULL,
    detalle     VARCHAR(120) NOT NULL DEFAULT '',
    creada_en   TIMESTAMP WITH TIME ZONE NOT NULL,
    pagada_en   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_deuda_negocio_venta UNIQUE (negocio_id, venta_uid),
    CONSTRAINT ck_deuda_monto CHECK (monto > 0)
);
CREATE INDEX ix_deuda_negocio_pagada ON deuda (negocio_id, pagada_en);
