-- Meta propia del trabajador: cuántos granizados se siente capaz de vender hoy. La escoge él al empezar el día y la
-- puede subir cuando la cumple («¿vas por más?»). No paga nada por sí misma: lo que paga son los premios por escalón.
CREATE TABLE meta_vendedor (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id  BIGINT       NOT NULL DEFAULT 1,
    vendedor_id BIGINT       NOT NULL REFERENCES vendedor (id),
    dia         DATE         NOT NULL,
    meta        INT          NOT NULL,
    creada_en   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_meta_vendedor_dia UNIQUE (negocio_id, vendedor_id, dia),
    CONSTRAINT ck_meta_vendedor CHECK (meta > 0)
);
