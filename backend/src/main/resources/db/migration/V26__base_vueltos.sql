-- Base para vueltos: plata en efectivo que el dueño le pasa de la caja a un trabajador para que tenga con qué devolver.
-- No es venta ni ganancia: al cerrar el día el trabajador la devuelve junto con el efectivo que recaudó.
CREATE TABLE base_vendedor (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id  BIGINT       NOT NULL DEFAULT 1,
    vendedor_id BIGINT       NOT NULL REFERENCES vendedor (id),
    dia         DATE         NOT NULL,
    monto       BIGINT       NOT NULL,
    creada_en   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_base_vendedor_monto CHECK (monto > 0)
);
CREATE INDEX ix_base_vendedor ON base_vendedor (negocio_id, vendedor_id, dia);
