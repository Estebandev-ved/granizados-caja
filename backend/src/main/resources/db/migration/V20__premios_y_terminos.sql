-- Premios por escalón (el trabajador gana más mientras más granizados vende en el día), granizados de regalo por día
-- y los términos del trabajo, que cada trabajador acepta y quedan guardados como constancia.
CREATE TABLE aceptacion_terminos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id    BIGINT       NOT NULL DEFAULT 1,
    vendedor_id   BIGINT       NOT NULL REFERENCES vendedor (id),
    -- Huella del texto aceptado: si cambian las tarifas o los premios, cambia y hay que aceptar otra vez
    version       VARCHAR(64)  NOT NULL,
    texto         VARCHAR(8000) NOT NULL,
    aceptada_en   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_aceptacion_terminos UNIQUE (negocio_id, vendedor_id, version)
);

