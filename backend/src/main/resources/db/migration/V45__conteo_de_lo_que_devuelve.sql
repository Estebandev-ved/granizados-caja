-- El dueño cuenta los granizados que le devuelve el trabajador al terminar el día y la app los compara con lo que
-- debería quedarle (lo que llevó menos lo que anotó). Lo que falte se le descuenta como faltante (venta FALTANTE).
-- Cada conteo queda como constancia: qué se esperaba, qué devolvió y cuánto se le descontó.
CREATE TABLE conteo_carga (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id  BIGINT        NOT NULL DEFAULT 1,
    vendedor_id BIGINT        NOT NULL REFERENCES vendedor (id),
    dia         DATE          NOT NULL,
    contado_en  TIMESTAMP WITH TIME ZONE NOT NULL,
    esperaba    INT           NOT NULL,
    devolvio    INT           NOT NULL,
    faltaron    INT           NOT NULL,
    sobraron    INT           NOT NULL,
    cobrado     BIGINT        NOT NULL,
    detalle     VARCHAR(1000) NOT NULL
);
CREATE INDEX ix_conteo_carga ON conteo_carga (negocio_id, vendedor_id, dia);
