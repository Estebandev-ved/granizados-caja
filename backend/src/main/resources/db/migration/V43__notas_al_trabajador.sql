-- Notas del dueño al trabajador: recordatorios o avisos cortos («mañana se empieza a las 8», «cuida los vasos»).
-- El trabajador las ve en Mi día (con un punto en la pestaña mientras tenga sin leer) y toca «Listo, la leí»:
-- `leida_en` queda con la hora, así el dueño sabe que la leyó.
CREATE TABLE nota_vendedor (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id  BIGINT       NOT NULL DEFAULT 1,
    vendedor_id BIGINT       NOT NULL REFERENCES vendedor (id),
    texto       VARCHAR(300) NOT NULL,
    creada_en   TIMESTAMP WITH TIME ZONE NOT NULL,
    leida_en    TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_nota_vendedor ON nota_vendedor (negocio_id, vendedor_id, creada_en);
