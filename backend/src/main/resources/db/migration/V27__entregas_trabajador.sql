-- Entregas del trabajador al dueño: el trabajador dice "ya te entregué $X" y el dueño confirma si es verdad.
-- Solo deja constancia: no mueve caja, Nequi ni ganancia.
CREATE TABLE entrega_vendedor (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id    BIGINT       NOT NULL DEFAULT 1,
    vendedor_id   BIGINT       NOT NULL REFERENCES vendedor (id),
    dia           DATE         NOT NULL,
    monto         BIGINT       NOT NULL,
    efectivo      BIGINT       NOT NULL DEFAULT 0,
    nequi         BIGINT       NOT NULL DEFAULT 0,
    transferencia BIGINT       NOT NULL DEFAULT 0,
    estado        VARCHAR(16)  NOT NULL,
    creada_en     TIMESTAMP WITH TIME ZONE NOT NULL,
    respondida_en TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_entrega_vendedor_monto CHECK (monto > 0)
);
CREATE INDEX ix_entrega_vendedor ON entrega_vendedor (negocio_id, vendedor_id, creada_en);
