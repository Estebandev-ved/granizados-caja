-- Pagos a trabajadores: el dueño marca "ya le pagué" con el monto de sus comisiones y premios; las cuentas del trabajador
-- se reinician desde ese corte. El trabajador confirma que le pagaron (en efectivo, firmando el paz y salvo).
CREATE TABLE pago_vendedor (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    negocio_id    BIGINT       NOT NULL DEFAULT 1,
    vendedor_id   BIGINT       NOT NULL REFERENCES vendedor (id),
    metodo        VARCHAR(10)  NOT NULL,
    estado        VARCHAR(12)  NOT NULL,
    monto         BIGINT       NOT NULL,
    comision      BIGINT       NOT NULL,
    bonos         BIGINT       NOT NULL,
    unidades      INT          NOT NULL,
    total_vendido BIGINT       NOT NULL,
    efectivo      BIGINT       NOT NULL,
    -- El corte: las cuentas siguientes cuentan ventas posteriores a `hasta`
    desde         TIMESTAMP WITH TIME ZONE,
    hasta         TIMESTAMP WITH TIME ZONE NOT NULL,
    creado_en     TIMESTAMP WITH TIME ZONE NOT NULL,
    respondido_en TIMESTAMP WITH TIME ZONE,
    -- Paz y salvo (solo pagos en efectivo): el texto exacto que firmó y con qué nombre
    texto         VARCHAR(4000),
    firma         VARCHAR(80),
    CONSTRAINT ck_pago_vendedor_metodo CHECK (metodo IN ('EFECTIVO', 'NEQUI')),
    CONSTRAINT ck_pago_vendedor_estado CHECK (estado IN ('PENDIENTE', 'CONFIRMADO', 'DISPUTADO', 'ANULADO'))
);
CREATE INDEX ix_pago_vendedor ON pago_vendedor (negocio_id, vendedor_id, hasta);
